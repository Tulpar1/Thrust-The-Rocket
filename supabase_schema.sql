create table public.scores (
    id bigint generated by default as identity primary key,
    player_name text not null check (char_length(player_name) between 1 and 20),
    score integer not null,
    apogee double precision not null,
    altitude_accuracy double precision not null,
    touchdown_speed double precision not null,
    damage_amount double precision not null default 0,
    failure_type text not null default 'NONE',
    status text not null check (status in ('LANDED', 'DAMAGED', 'CRASHED')),
    created_at timestamptz not null default now()
);

create index scores_score_idx on public.scores (score desc);
create index scores_created_at_idx on public.scores (created_at desc);

alter table public.scores enable row level security;
